const mockFs = require('mock-fs');
const crypto = require('crypto');
const filesToMarkdown = require('../src/filesToMarkdown');

describe('filesToMarkdown', () => {
  afterEach(() => {
    mockFs.restore();
  });

  test('should generate markdown with header', () => {
    mockFs({
      '/project': {
        'index.js': 'console.log("hello");'
      }
    });

    const result = filesToMarkdown('/project', ['index.js']);

    expect(result.markdown).toContain('# AI-ContextGen Snapshot');
    expect(result.markdown).toContain('> Generated by AI-ContextGen');
  });

  test('should include file content with checksum', () => {
    const content = 'console.log("hello");';
    mockFs({
      '/project': {
        'index.js': content
      }
    });

    const expectedChecksum = crypto.createHash('sha256').update(content).digest('hex');
    const result = filesToMarkdown('/project', ['index.js']);

    expect(result.markdown).toContain('## `index.js`');
    expect(result.markdown).toContain(`checksum: ${expectedChecksum}`);
    expect(result.markdown).toContain('```js');
    expect(result.markdown).toContain(content);
    expect(result.markdown).toContain('```');
  });

  test('should generate global checksum', () => {
    mockFs({
      '/project': {
        'index.js': 'console.log("hello");'
      }
    });

    const result = filesToMarkdown('/project', ['index.js']);

    expect(result.globalChecksum).toBeDefined();
    expect(result.globalChecksum).toMatch(/^[a-f0-9]{64}$/);
    expect(result.markdown).toContain(`Global checksum: ${result.globalChecksum}`);
  });

  test('should skip binary files', () => {
    mockFs({
      '/project': {
        'image.png': Buffer.from([0x89, 0x50, 0x4e, 0x47]),
        'index.js': 'code'
      }
    });

    const result = filesToMarkdown('/project', ['image.png', 'index.js']);

    expect(result.markdown).not.toContain('image.png');
    expect(result.markdown).toContain('index.js');
    expect(result.processedCount).toBe(1);
  });

  test('should skip files larger than 1MB', () => {
    const largeContent = 'x'.repeat(1024 * 1024 + 1);
    mockFs({
      '/project': {
        'large.js': largeContent,
        'small.js': 'small content'
      }
    });

    const result = filesToMarkdown('/project', ['large.js', 'small.js']);

    expect(result.markdown).not.toContain('large.js');
    expect(result.markdown).toContain('small.js');
    expect(result.processedCount).toBe(1);
  });

  test('should use correct language for syntax highlighting', () => {
    mockFs({
      '/project': {
        'script.js': 'js code',
        'styles.css': 'css code',
        'data.json': '{}',
        'readme.md': '# readme'
      }
    });

    const result = filesToMarkdown('/project', ['script.js', 'styles.css', 'data.json', 'readme.md']);

    expect(result.markdown).toContain('```js');
    expect(result.markdown).toContain('```css');
    expect(result.markdown).toContain('```json');
    expect(result.markdown).toContain('```md');
  });

  test('should include file separator between files', () => {
    mockFs({
      '/project': {
        'file1.js': 'content1',
        'file2.js': 'content2'
      }
    });

    const result = filesToMarkdown('/project', ['file1.js', 'file2.js']);

    const separatorCount = (result.markdown.match(/###==AICG_FILE==###/g) || []).length;
    // One before each file + one at the end
    expect(separatorCount).toBe(3);
  });

  test('should call progress callback', () => {
    mockFs({
      '/project': {
        'file1.js': 'a',
        'file2.js': 'b'
      }
    });

    const progressCalls = [];
    filesToMarkdown('/project', ['file1.js', 'file2.js'], (current, total) => {
      progressCalls.push({ current, total });
    });

    expect(progressCalls).toHaveLength(2);
    expect(progressCalls[0]).toEqual({ current: 1, total: 2 });
    expect(progressCalls[1]).toEqual({ current: 2, total: 2 });
  });

  test('should handle files with no extension', () => {
    mockFs({
      '/project': {
        'Makefile': 'all: build'
      }
    });

    const result = filesToMarkdown('/project', ['Makefile']);

    expect(result.markdown).toContain('```text');
  });
});
