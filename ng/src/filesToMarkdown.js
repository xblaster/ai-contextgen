const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

// Binary file extensions to skip
const BINARY_EXTENSIONS = new Set([
  '.png', '.jpg', '.jpeg', '.gif', '.svg', '.ico',
  '.exe', '.dll', '.zip', '.tar', '.gz',
  '.mp4', '.mp3', '.ogg', '.mov',
  '.pdf', '.webp',
  '.woff', '.woff2', '.ttf', '.eot', '.otf'
]);

// Maximum file size (1MB)
const MAX_SIZE = 1024 * 1024;

// File separator
const FILE_SEPARATOR = '###==AICG_FILE==###';

/**
 * Converts a list of files to Markdown format with checksums
 * @param {string} baseDir - Base directory containing files
 * @param {string[]} files - Array of relative file paths
 * @param {Function} [onProgress] - Optional progress callback (current, total)
 * @returns {Object} { markdown: string, globalChecksum: string, processedCount: number }
 */
function filesToMarkdown(baseDir, files, onProgress) {
  const sections = [];
  const checksumParts = [];
  let processedCount = 0;

  // Header
  sections.push('# AI-ContextGen Snapshot');
  sections.push('> Generated by AI-ContextGen');
  sections.push('');

  for (let i = 0; i < files.length; i++) {
    const relativePath = files[i];
    const fullPath = path.join(baseDir, relativePath);
    const ext = path.extname(relativePath).toLowerCase();

    // Skip binary files
    if (BINARY_EXTENSIONS.has(ext)) {
      if (onProgress) onProgress(i + 1, files.length);
      continue;
    }

    // Check file size
    let stats;
    try {
      stats = fs.statSync(fullPath);
    } catch (err) {
      if (onProgress) onProgress(i + 1, files.length);
      continue;
    }

    if (stats.size > MAX_SIZE) {
      if (onProgress) onProgress(i + 1, files.length);
      continue;
    }

    // Read file content
    let content;
    try {
      content = fs.readFileSync(fullPath, 'utf-8');
    } catch (err) {
      if (onProgress) onProgress(i + 1, files.length);
      continue;
    }

    // Calculate checksum
    const checksum = crypto.createHash('sha256').update(content).digest('hex');
    checksumParts.push(`${relativePath}:${checksum}`);

    // Determine language for syntax highlighting
    const lang = ext.slice(1) || 'text';

    // Build Markdown section
    sections.push(FILE_SEPARATOR);
    sections.push('');
    sections.push(`## \`${relativePath}\` (checksum: ${checksum})`);
    sections.push('');
    sections.push('```' + lang);
    sections.push(content);
    sections.push('```');
    sections.push('');

    processedCount++;
    if (onProgress) onProgress(i + 1, files.length);
  }

  // Calculate global checksum
  const globalChecksum = crypto.createHash('sha256')
    .update(checksumParts.join('\n'))
    .digest('hex');

  // Footer
  sections.push(FILE_SEPARATOR);
  sections.push('');
  sections.push(`Global checksum: ${globalChecksum}`);

  return {
    markdown: sections.join('\n'),
    globalChecksum,
    processedCount
  };
}

module.exports = filesToMarkdown;
